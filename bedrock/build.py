#!/usr/bin/env python3
"""Builds the Bedrock edition of Stone Golem.

- injects bedrock/balance.json into the packs ({{NAME}} placeholders) and generates BP/scripts/balance.js
- copies the textures from the Java edition's resources (single source of truth, see tools/generate_textures.py);
  the MIT license is declared in each manifest's metadata (no extra LICENSE file inside the packs)
- validates every JSON file and fails on leftover placeholders
- writes bedrock/build/StoneGolem_BP, bedrock/build/StoneGolem_RP and bedrock/dist/StoneGolem-<version>.mcaddon

Usage: python3 bedrock/build.py   (standard library only)
"""
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
JAVA_ASSETS = ROOT / "common/src/main/resources/assets/stonegolem/textures"
BUILD = HERE / "build"
DIST = HERE / "dist"
PACKS = {"BP": "StoneGolem_BP", "RP": "StoneGolem_RP"}

TEXTURES = {
    "RP/textures/entity/stone_golem/stone_golem.png": JAVA_ASSETS / "entity/stone_golem/stone_golem.png",
    "RP/textures/entity/rising_rock.png": JAVA_ASSETS / "entity/rising_rock.png",
    "RP/textures/items/golem_core.png": JAVA_ASSETS / "item/golem_core.png",
    "BP/pack_icon.png": ROOT / "common/src/main/resources/stonegolem.png",
    "RP/pack_icon.png": ROOT / "common/src/main/resources/stonegolem.png",
}


def load_balance():
    balance = {k: v for k, v in json.loads((HERE / "balance.json").read_text()).items() if not k.startswith("_")}
    for name in ("ROCK_RISE", "ROCK_HOLD", "ROCK_SINK"):
        balance[f"{name}_SECONDS"] = balance[f"{name}_TICKS"] / 20
    return balance


def substitute(text, balance, path):
    def value(match):
        key = match.group(1)
        if key not in balance:
            sys.exit(f"{path}: unknown placeholder {{{{{key}}}}}")
        return json.dumps(balance[key])

    text = re.sub(r'"\{\{(\w+)\}\}"', value, text)  # whole JSON value -> number
    text = re.sub(r"\{\{(\w+)\}\}", lambda m: str(balance.get(m.group(1), m.group(0))), text)  # inside strings (Molang)
    if "{{" in text:
        sys.exit(f"{path}: unresolved placeholder")
    return text


def main():
    balance = load_balance()
    balance["VERSION"] = ".".join(map(str, json.loads((HERE / "packs/BP/manifest.json").read_text())["header"]["version"]))
    shutil.rmtree(BUILD, ignore_errors=True)
    for src, name in PACKS.items():
        for file in (HERE / "packs" / src).rglob("*"):
            if file.is_dir():
                continue
            out = BUILD / name / file.relative_to(HERE / "packs" / src)
            out.parent.mkdir(parents=True, exist_ok=True)
            if file.suffix in (".json", ".js", ".lang"):
                text = substitute(file.read_text(encoding="utf-8"), balance, file)
                if file.suffix == ".json":
                    json.loads(text)  # validate
                out.write_text(text, encoding="utf-8")
            else:
                shutil.copy2(file, out)

    (BUILD / PACKS["BP"] / "scripts/balance.js").write_text(
        "// Generated by bedrock/build.py from bedrock/balance.json - do not edit.\n"
        f"export const B = Object.freeze({json.dumps(balance, indent=2)});\n", encoding="utf-8")
    for dest, src in TEXTURES.items():
        pack, rel = dest.split("/", 1)
        out = BUILD / PACKS[pack] / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, out)

    version = ".".join(map(str, json.loads((HERE / "packs/BP/manifest.json").read_text())["header"]["version"]))
    DIST.mkdir(exist_ok=True)
    addon = DIST / f"StoneGolem-{version}.mcaddon"
    with zipfile.ZipFile(addon, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in PACKS.values():
            # Directory entries included, like archives produced by Minecraft itself and common tools.
            zf.write(BUILD / name, name + "/")
            for file in sorted((BUILD / name).rglob("*")):
                zf.write(file, file.relative_to(BUILD).as_posix() + ("/" if file.is_dir() else ""))
    print(f"Built {addon.relative_to(ROOT)} ({addon.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
